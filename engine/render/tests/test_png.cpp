u32 px(u32 x, u32 y, bool alpha) {
    const u32 r = (x * 37 + y * 11) & 255u;
    const u32 g = (x * x + y * 29) & 255u;
    const u32 b = ((x ^ y) * 17) & 255u;
    const u32 a = alpha ? ((255u - x * 9 - y * 5) & 255u) : 255u;
    return r | (g << 8) | (b << 16) | (a << 24);
}

void check_formula(const png::Image& img, u32 w, u32 h, bool alpha) {
    REQUIRE(img.width == w);
    REQUIRE(img.height == h);
    REQUIRE(img.pixels.size() == static_cast<std::size_t>(w) * h);
    for (u32 y = 0; y < h; ++y)
        for (u32 x = 0; x < w; ++x)
            if (img.pixels[y * w + x] != px(x, y, alpha))
                FAIL("pixel " << x << "," << y);
}

// Noise with structure, so the encoder finds both literals and long matches.
std::vector<u32> test_image(u32 w, u32 h, u32 seed) {
    std::vector<u32> v(static_cast<std::size_t>(w) * h);
    u32 s = seed;
    for (u32 y = 0; y < h; ++y)
        for (u32 x = 0; x < w; ++x) {
            s = s * 1664525u + 1013904223u;
            const u32 noise = (s >> 24) & 0x0Fu;
            v[y * w + x] = ((x * 3 + noise) & 255u) | (((y * 5) & 255u) << 8) |
                           ((((x / 8 + y / 8) & 1u) ? 200u : 40u) << 16) |
                           ((x < w / 2 ? 255u : (x * 13) & 255u) << 24);
        }
    return v;
}

